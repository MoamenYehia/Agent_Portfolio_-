from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any

class ChatRequest(BaseModel):
    message: str = Field(
        ..., 
        description="The query or message sent by the user.",
        example="What projects did Moamen build using PyTorch?"
    )
    thread_id: Optional[str] = Field(
        default="default_session", 
        description="Session identifier used for memory and multi-turn chat tracking.",
        example="session_101"
    )

class ChatResponse(BaseModel):
    response: str = Field(..., description="The final answer generated by the agent.")
    thread_id: str = Field(..., description="The active session thread ID.")
    status: str = Field(default="success", description="Execution status of the API request.")

class HealthResponse(BaseModel):
    status: str
    service: str